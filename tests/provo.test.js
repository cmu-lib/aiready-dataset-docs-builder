// Unit tests for the PROV-O generator. Validation tests come with 3.2.
// Run with:  npm test

import { test } from 'vitest';
import assert from 'node:assert/strict';

import { generateProvo, effectiveProvo, PROVO_CONTEXT } from '../src/generators/provo.js';

const findById = (g, id) => g.find((n) => n['@id'] === id);
const hasType = (n, t) => n['@type'] === t || (Array.isArray(n['@type']) && n['@type'].includes(t));

test('generateProvo emits prov @context and a dataset entity generated by curation', () => {
  const desc = generateProvo({ pathway: 'C', answers: {} });
  assert.equal(desc['@context'].prov, PROVO_CONTEXT.prov);
  const ds = findById(desc['@graph'], '#dataset');
  assert.ok(ds && hasType(ds, 'prov:Entity'));
  assert.deepEqual(ds['prov:wasGeneratedBy'], { '@id': '#activity-curation' });
});

test('dataset entity @id uses the DOI URL when a persistent id is present', () => {
  const desc = generateProvo({
    pathway: 'C',
    answers: { 'fairness.l1.persistent_id': { value: '10.5281/zenodo.123' } },
  });
  assert.ok(findById(desc['@graph'], 'https://doi.org/10.5281/zenodo.123'));
});

test('agent (from role) and curation activity (with software) are scaffolded', () => {
  const desc = generateProvo({
    pathway: 'C',
    answers: {
      'provenance.l3.agents_with_roles': { value: 'data_steward' },
      'provenance.l2.transformations_documented': { value: 'Cleaned and harmonised.' },
      'provenance.l2.software_versions': { value: 'python 3.11; pandas 2.2' },
    },
  });
  const agent = findById(desc['@graph'], '#agent');
  assert.ok(hasType(agent, 'prov:Agent'));
  assert.equal(agent.role, 'data_steward');
  assert.match(agent['rdfs:label'], /Data steward/);

  const act = findById(desc['@graph'], '#activity-curation');
  assert.match(act.software, /python 3\.11/);
  assert.match(act['rdfs:comment'], /Cleaned/);
  assert.deepEqual(act['prov:wasAssociatedWith'], { '@id': '#agent' });
});

test('no agent node when no role is declared; scaffold has no variable entities', () => {
  const desc = generateProvo({ pathway: 'C', answers: {} });
  assert.ok(!findById(desc['@graph'], '#agent'));
  assert.ok(!desc['@graph'].some((n) => n.kind === 'variable'));
});

const modelRecord = () => ({
  pathway: 'C',
  answers: {},
  provenance: {
    sources: [{ id: 's1', name: 'Raw EHR export' }],
    steps: [
      {
        id: 'st1',
        label: 'Cleaning',
        inputs: ['s1'],
        outputs: [{ id: 'o1', name: 'age' }],
        software: 'python 3.11',
        agentRole: 'data_steward',
      },
    ],
  },
});

test('generateProvo composes from the step model (source, activity, derived output, agent)', () => {
  const g = generateProvo(modelRecord())['@graph'];
  assert.ok(findById(g, '#source/s1'));
  const act = findById(g, '#activity/st1');
  assert.deepEqual(act['prov:used'], { '@id': '#source/s1' });
  assert.deepEqual(act['prov:wasAssociatedWith'], { '@id': '#agent/data_steward' });
  const out = findById(g, '#var/o1');
  assert.equal(out.kind, 'variable');
  assert.deepEqual(out['prov:wasDerivedFrom'], { '@id': '#source/s1' });
  assert.deepEqual(out['prov:wasGeneratedBy'], { '@id': '#activity/st1' });
  assert.ok(findById(g, '#agent/data_steward'));
});

test('effectiveProvo returns the edited record when present', () => {
  const edited = { '@context': PROVO_CONTEXT, '@graph': [{ '@id': '#x', '@type': 'prov:Entity' }] };
  assert.equal(effectiveProvo({ provo: edited }), edited);
  assert.ok(effectiveProvo({ answers: {} })['@graph']); // falls back to generated
});
